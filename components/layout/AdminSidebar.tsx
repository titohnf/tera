function NavLink({ href, label, icon, alsoMatch, pathname }: NavItem & { pathname: string }) {
  const isActive = href === '/admin'
    ? pathname === '/admin'
    : pathname.startsWith(href) || (!!alsoMatch && pathname.startsWith(alsoMatch))
  return (
    <Link
      href={href}
      className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
        isActive ? 'bg-blue-50 text-blue-700' : 'text-gray-600 hover:bg-blue-50/50'
      }`}
    >
      {icon}
      {label}
    </Link>
  )
}

